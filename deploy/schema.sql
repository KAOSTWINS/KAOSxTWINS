-- Cloudflare D1 database for KAOSTWINS community.
CREATE TABLE IF NOT EXISTS votes (voter_id TEXT PRIMARY KEY, choice TEXT NOT NULL, updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE INDEX IF NOT EXISTS idx_votes_choice ON votes(choice);
CREATE TABLE IF NOT EXISTS requests (id INTEGER PRIMARY KEY AUTOINCREMENT, title TEXT NOT NULL, pitch TEXT NOT NULL, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);
